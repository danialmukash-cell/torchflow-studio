"""Deterministic PyTorch nn.Module code generation.

Every emitted line is produced from a fixed template driven by the
validated graph. No user-supplied string reaches an identifier or a
code line without validation:

  * the class name is validated as a Python identifier and rejected if
    it is a keyword;
  * layer attributes are always `layer_{n}` where n is a small int;
  * param values are already range-checked by validation.py, and we
    format them with repr() to keep the output stable and valid Python.

The function returns text. It is NEVER exec'd by the server.
"""

from __future__ import annotations

import keyword

from .schemas import GraphDocument, GraphNode
from .validation import ShapeError

LAYER_TYPES = {"linear", "relu", "sigmoid", "tanh", "flatten", "dropout"}
RESERVED_CLASS_NAMES = {"nn", "torch"}


def _validate_class_name(name: str) -> str:
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ShapeError(
            f'"{name}" is not a valid Python class name. Use letters, digits, '
            "and underscores; the name must start with a letter."
        )
    if name in RESERVED_CLASS_NAMES:
        raise ShapeError(f'"{name}" is a reserved name; choose another.')
    return name


def _fmt_number(value: object) -> str:
    """Stable, valid-Python formatting for numeric params."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        # repr() is round-trippable and always valid Python.
        return repr(value)
    raise ShapeError(f"Cannot format value of type {type(value).__name__}.")


def _emit_layer_init(node: GraphNode, attr: str, in_shape: tuple[int, ...]) -> str:
    t = node.type

    if t == "linear":
        out_features = int(node.params.get("out_features", 128))
        bias = bool(node.params.get("bias", True))
        return (
            f"        self.{attr} = nn.Linear("
            f"{in_shape[0]}, {out_features}, bias={_fmt_number(bias)})"
        )
    if t == "relu":
        return f"        self.{attr} = nn.ReLU()"
    if t == "sigmoid":
        return f"        self.{attr} = nn.Sigmoid()"
    if t == "tanh":
        return f"        self.{attr} = nn.Tanh()"
    if t == "flatten":
        return f"        self.{attr} = nn.Flatten()"
    if t == "dropout":
        p = float(node.params.get("p", 0.5))
        return f"        self.{attr} = nn.Dropout(p={_fmt_number(p)})"
    raise ShapeError(f"Node type {t} cannot be emitted as a layer.")  # pragma: no cover


def generate_code(
    doc: GraphDocument,
    shapes: dict[str, list[int]],
    class_name: str = "TorchFlowModel",
) -> str:
    """Build a complete, self-contained Python module string."""
    class_name = _validate_class_name(class_name)

    by_id = {n.id: n for n in doc.nodes}
    outgoing = {n.id: [] for n in doc.nodes}
    for edge in doc.edges:
        outgoing[edge.source].append(edge)

    input_node = next(n for n in doc.nodes if n.type == "input")

    # Walk the chain in topological order.
    order: list[GraphNode] = []
    current = input_node
    while True:
        order.append(current)
        if current.type == "output":
            break
        next_id = outgoing[current.id][0].target
        current = by_id[next_id]

    # Only layer nodes become nn.Module children.
    layer_nodes = [n for n in order if n.type in LAYER_TYPES]

    init_lines: list[str] = []
    forward_lines: list[str] = ["    def forward(self, x):"]

    if not layer_nodes:
        forward_lines.append("        return x")
    else:
        for index, node in enumerate(layer_nodes, start=1):
            attr = f"layer_{index}"
            in_shape = tuple(shapes[order[order.index(node) - 1].id])
            init_lines.append(_emit_layer_init(node, attr, in_shape))
            forward_lines.append(f"        x = self.{attr}(x)")
        forward_lines.append("        return x")

    lines: list[str] = [
        '# Model generated by TorchFlow Studio.',
        '# Graph name (escaped): ' + ascii(doc.name),
        f'# Schema: v{doc.schemaVersion}',
        "",
        "import torch",
        "import torch.nn as nn",
        "",
        "",
        f"class {class_name}(nn.Module):",
        "    def __init__(self):",
        "        super().__init__()",
    ]
    lines.extend(init_lines if init_lines else ["        pass"])
    lines.append("")
    lines.extend(forward_lines)
    lines.append("")
    return "\n".join(lines)
