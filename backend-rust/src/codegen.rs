use crate::graph::Layer;
use std::fmt::Write;
use unicode_ident::{is_xid_continue, is_xid_start};
use unicode_normalization::UnicodeNormalization;

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

fn check_class_name(name: &str) -> Result<(), String> {
    let mut chars = name.chars();
    if !chars.next().is_some_and(|c| c == '_' || is_xid_start(c))
        || !chars.all(is_xid_continue)
        || KEYWORDS.contains(&name)
    {
        return Err(format!("{name:?} is not a valid Python class name. Use a Python identifier that is not a keyword."));
    }
    // Python normalizes identifiers, so an alias such as fullwidth ｎｎ would
    // shadow the import and make className disagree with the generated module.
    if !name.nfkc().eq(name.chars()) {
        return Err(format!("{name:?} is not a normalized Python class name."));
    }
    if ["nn", "torch", "__debug__"].contains(&name) {
        return Err(format!("{name:?} is a reserved name; choose another."));
    }
    Ok(())
}

pub fn generate(graph_name: &str, layers: &[Layer], class_name: &str) -> Result<String, String> {
    check_class_name(class_name)?;
    let name: String = graph_name.escape_default().collect();
    let mut code = format!(
        "# Model generated by TorchFlow Studio.\n# Graph name (escaped): {name}\n# Schema: v1\n\nimport torch\nimport torch.nn as nn\n\n\nclass {class_name}(nn.Module):\n    def __init__(self):\n        super().__init__()\n"
    );
    if layers.is_empty() {
        code.push_str("        pass\n");
    }
    for (i, layer) in layers.iter().enumerate() {
        let expression = match layer {
            Layer::Linear {
                input,
                output,
                bias,
            } => format!(
                "nn.Linear({input}, {output}, bias={})",
                if *bias { "True" } else { "False" },
            ),
            Layer::Relu => "nn.ReLU()".into(),
            Layer::Sigmoid => "nn.Sigmoid()".into(),
            Layer::Tanh => "nn.Tanh()".into(),
            Layer::Flatten => "nn.Flatten()".into(),
            Layer::Dropout(p) => format!("nn.Dropout(p={p:?})"),
        };
        writeln!(code, "        self.layer_{} = {expression}", i + 1).unwrap();
    }
    code.push_str("\n    def forward(self, x):\n");
    for i in 1..=layers.len() {
        writeln!(code, "        x = self.layer_{i}(x)").unwrap();
    }
    code.push_str("        return x\n");
    Ok(code)
}

#[cfg(test)]
mod tests {
    use super::generate;

    #[test]
    fn rejects_identifier_aliases_and_reserved_names() {
        assert!(generate("Graph", &[], "ｎｎ").is_err());
        assert!(generate("Graph", &[], "__debug__").is_err());
        assert!(generate("Graph", &[], "Модель_1").is_ok());
    }
}
